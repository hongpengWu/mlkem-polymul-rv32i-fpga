"""Freeze and archive the PS-controlled overlay; EDA stages live in vivado_bd.tcl."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import runpy
import shutil
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[2]


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def dump(path, data):
    Path(path).write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def prepare(run, reuse_sim=None):
    snapshot = run / "snapshot"
    if snapshot.exists():
        raise RuntimeError("Use a new run directory; frozen inputs already exist")
    build_path = ROOT / "results/keccak_cpu/ps/build.json"
    build = json.loads(build_path.read_text(encoding="utf-8"))
    for name, digest in build["source_sha256"].items():
        if sha(ROOT / name) != digest:
            raise RuntimeError("Stale PS firmware source: " + name)
    firmware = ROOT / build["firmware"]
    if sha(firmware) != build["firmware_sha256"]:
        raise RuntimeError("PS firmware hash mismatch")
    pairs = [(firmware, "ps.mem"), (build_path, "build.json")]
    pairs += [(ROOT / name, "source/" + name) for name in build["source_sha256"]]
    pairs += [(ROOT / "rtl/cpu/picorv32.v", "rtl/picorv32.v")]
    for name in ("mlkem1024_keccak_system.sv", "keccak_mmio_adapter.sv", "mlkem1024_keccak_axi.sv"):
        pairs.append((ROOT / "rtl/accelerator" / name, "rtl/" + name))
    pairs += [(ROOT / "tb/accelerator/tb_mlkem1024_keccak_axi.sv", "tb/tb_mlkem1024_keccak_axi.sv"),
              (ROOT / "scripts/mlkem1024_keccak/vivado_bd.tcl", "vivado_bd.tcl"),
              (Path(__file__), "pynq_overlay.py")]
    # Selected generated HLS files must remain identical to the verified kernel.
    proof_path = ROOT / "results/keccak_cpu/kat/batches/pilot_000_001_115/20260927_171430_546316/manifest.json"
    proof = json.loads(proof_path.read_text(encoding="utf-8"))
    for name, info in proof["inputs"].items():
        if name.startswith("hls/"):
            source = Path(proof["run_dir"]) / "snapshot" / name
            if sha(source) != info["sha256"]:
                raise RuntimeError("Verified HLS input changed: " + name)
            pairs.append((source, name))
    pairs.append((proof_path, "hls_provenance.json"))
    for name in ("mlkem1024.py", "mlkem1024.ipynb"):
        pairs.append((ROOT / "pynq/mlkem1024" / name, "host/" + name))
    board_dir = Path("E:/Xilinx/Vivado/2024.2/data/boards/board_files/pynq-z2/A.0")
    for name in ("board.xml", "preset.xml", "part0_pins.xml"):
        pairs.append((board_dir / name, "board_preset/" + name))
    records = {}
    for source, name in pairs:
        target = snapshot / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        records[name] = dict(source=str(source), sha256=sha(target))
    xdc = snapshot / "overlay_io.xdc"
    xdc.write_text("\n".join([
        f"set_property -dict {{PACKAGE_PIN {pin} IOSTANDARD LVCMOS33}} [get_ports {{led[{i}]}}]"
        for i, pin in enumerate(("R14", "P14", "N16", "M14"))] + [
        "set_false_path -to [get_ports {led[*]}]",
        "set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]",
        "set_property CONFIG_VOLTAGE 3.3 [current_design]",
        "set_property CFGBVS VCCO [current_design]", ""]), encoding="ascii")
    records[xdc.name] = dict(source="Generated by frozen pynq_overlay.py", sha256=sha(xdc))
    subprocess.run([sys.executable, "-E", str(snapshot / "host/mlkem1024.py"),
                    "--prepare", "--root", str(ROOT), "--output", str(snapshot / "host")], check=True)
    records["host/kat_vectors.json"] = dict(source="Pinned ACVP package generated before EDA",
                                          sha256=sha(snapshot / "host/kat_vectors.json"))
    sys.path.insert(0, str(ROOT / "scripts/kat"))
    from package_mlkem import load_cases, pack_fixture, verify_roundtrip
    from copy import deepcopy
    all_cases, _ = load_cases(ROOT, 1024)
    indices = [0, 1, 115]
    cases = deepcopy([all_cases[i] for i in indices])
    for i, case in enumerate(cases):
        case["case_index"] = i
    for expected, direction in ((False, "input"), (True, "expected")):
        path = snapshot / f"board_{direction}.mem"
        words = pack_fixture(cases, 1024, expected)
        path.write_text("".join(f"{w:08x}\n" for w in words), encoding="ascii")
        verify_roundtrip(path, cases, 1024, expected)
        records[path.name] = dict(source="Pinned public ACVP, indices 0/1/115", sha256=sha(path))
    dump(run / "manifest.json", dict(run_dir=str(run), scope="PS AXI overlay candidate; not historical RTL or board evidence",
         created_utc=datetime.now(timezone.utc).isoformat(), official_indices=indices,
         inputs=records, firmware_sha256=sha(firmware), board_preset="tul.com.tw:pynq-z2:part0:1.0"))
    if reuse_sim:
        source = reuse_sim.resolve()
        prior = verify(source)
        keys = [k for k in records if k.startswith(("rtl/", "hls/", "tb/")) or
                k in ("ps.mem", "board_input.mem", "board_expected.mem")]
        for name in keys:
            if records[name]["sha256"] != prior["inputs"][name]["sha256"]:
                raise RuntimeError("Cannot reuse simulation: changed " + name)
        log = source / "simulate.log"
        if not log.is_file():
            log = source / "sim/axi_sim.sim/sim_1/behav/xsim/simulate.log"
        text = log.read_text(encoding="utf-8")
        if "AXI_KAT_PASS cases=3 starts=85" not in text or re.search(r"fatal:|ERROR:|AXI_KAT_FAIL", text, re.I):
            raise RuntimeError("Source simulation was not successful")
        shutil.copyfile(log, run / "simulate.log")
        dump(run / "simulation_reuse.json", dict(source_run=str(source),
             source_manifest_sha256=sha(source / "manifest.json"), log_sha256=sha(log),
             same_simulation_inputs=keys, scope="Same RTL/HLS/firmware/TB/fixtures; orchestration-only repair"))
    print("PYNQ_PREPARE_PASS " + str(run))


def verify(run):
    manifest = json.loads((run / "manifest.json").read_text(encoding="utf-8"))
    for name, info in manifest["inputs"].items():
        if sha(run / "snapshot" / name) != info["sha256"]:
            raise RuntimeError("Frozen input changed: " + name)
    return manifest


def bd_control_checks(run):
    """Independently inspect generated BD/XCI/HDL; do not trust timing success.

    In particular an active-low auxiliary reset tied to zero holds the whole
    AXI design in reset even when synthesis and physical implementation pass.
    This check is read-only and its input hashes identify the inspected files.
    """
    run = Path(run)
    reasons, details = [], {"input_sha256": {}, "reset": {}, "clock": {}, "address": {}}

    def check(condition, reason):
        if not condition:
            reasons.append(reason)

    def read(path, structured=True):
        details["input_sha256"][path.relative_to(run).as_posix()] = sha(path)
        text = path.read_text(encoding="utf-8")
        return json.loads(text) if structured else text

    def number(value):
        text = str(value)
        match = re.fullmatch(r"(\d+)([KMG])", text, re.I)
        if match:
            return int(match[1]) * (1024 ** ("KMG".index(match[2].upper()) + 1))
        return int(text, 0) if text.lower().startswith("0x") else int(text)

    try:
        paths = list((run / "project").glob("*.srcs/sources_1/bd/system/system.bd"))
        if len(paths) != 1:
            raise ValueError("Expected one generated system.bd, found " + str(len(paths)))
        bd_path = paths[0]
        design = read(bd_path)["design"]
        components, nets = design["components"], design["nets"]
        check(design["design_info"].get("validated") == "true", "Generated BD is not validated")
        xci_cache = {}

        def xci(cell):
            if cell not in xci_cache:
                xci_cache[cell] = read(bd_path.parent / components[cell]["xci_path"])["ip_inst"]
            return xci_cache[cell]

        def parameter(cell, name, section="component_parameters"):
            return xci(cell)["parameters"][section][name][0]["value"]

        def connected(*endpoints):
            matches = [set(net["ports"]) for net in nets.values()
                       if endpoints[0] in net.get("ports", [])]
            return len(matches) == 1 and set(endpoints).issubset(matches[0])

        def constant(endpoint):
            matches = [net["ports"] for net in nets.values() if endpoint in net.get("ports", [])]
            if len(matches) != 1:
                raise ValueError("Expected one net for " + endpoint)
            drivers = [port.split("/")[0] for port in matches[0] if port.endswith("/dout")
                       and components[port.split("/")[0]].get("vlnv", "").startswith("xilinx.com:ip:xlconstant:")]
            if len(drivers) != 1:
                raise ValueError("Expected one constant driver for " + endpoint)
            cell = drivers[0]
            value = number(parameter(cell, "CONST_VAL", "model_parameters"))
            check(number(parameter(cell, "CONST_WIDTH", "model_parameters")) == 1,
                  "Reset constant must be one bit: " + cell)
            check(number(parameter(cell, "CONST_VAL")) == value,
                  "Constant component/model disagree: " + cell)
            return cell, value

        ext = number(parameter("reset_100m", "C_EXT_RESET_HIGH", "model_parameters"))
        aux = number(parameter("reset_100m", "C_AUX_RESET_HIGH", "model_parameters"))
        aux_cell, aux_value = constant("reset_100m/aux_reset_in")
        debug_cell, debug_value = constant("reset_100m/mb_debug_sys_rst")
        lock_cell, lock_value = constant("reset_100m/dcm_locked")
        details["reset"] = dict(external_active_level=ext, auxiliary_active_level=aux,
                                auxiliary_constant=aux_value, auxiliary_driver=aux_cell,
                                debug_constant=debug_value, lock_constant=lock_value)
        check(ext == 0, "PS FCLK_RESET0_N requires C_EXT_RESET_HIGH=0")
        check(aux in (0, 1) and aux_value != aux,
              f"Auxiliary reset is permanently asserted: active_level={aux}, constant={aux_value}")
        check(debug_value == 0, "MicroBlaze debug reset must be tied inactive (0)")
        check(lock_value == 1, "Reset dcm_locked must be tied high for the PS FCLK")
        for name, value in (("C_EXT_RESET_HIGH", ext), ("C_AUX_RESET_HIGH", aux)):
            check(number(parameter("reset_100m", name)) == value,
                  "Reset component/model polarity disagree: " + name)
        check(connected("ps7/FCLK_RESET0_N", "reset_100m/ext_reset_in"),
              "External reset is not driven by PS FCLK_RESET0_N")
        check(connected("reset_100m/peripheral_aresetn", "k4_core/s_axi_aresetn",
                        "axi_bus/S00_ARESETN", "axi_bus/M00_ARESETN"), "Peripheral reset wiring mismatch")
        check(connected("reset_100m/interconnect_aresetn", "axi_bus/ARESETN"), "Interconnect reset wiring mismatch")

        clock_pins = ["ps7/M_AXI_GP0_ACLK", "axi_bus/ACLK", "axi_bus/S00_ACLK",
                      "axi_bus/M00_ACLK", "k4_core/s_axi_aclk", "reset_100m/slowest_sync_clk"]
        check(connected("ps7/FCLK_CLK0", *clock_pins), "Core/AXI/reset clocks are not all driven by FCLK_CLK0")
        for name in ("PCW_FPGA0_PERIPHERAL_FREQMHZ", "PCW_ACT_FPGA0_PERIPHERAL_FREQMHZ", "PCW_M_AXI_GP0_FREQMHZ"):
            frequency = float(parameter("ps7", name))
            details["clock"][name] = frequency
            check(frequency == 100.0, "PS clock configuration is not 100 MHz: " + name)
        for name in ("PCW_EN_CLK0_PORT", "PCW_EN_RST0_PORT", "PCW_USE_M_AXI_GP0"):
            check(number(parameter("ps7", name)) == 1, "Required PS port disabled: " + name)
        core = components["k4_core"]
        check(core["reference_info"]["ref_name"] == "mlkem1024_keccak_axi", "Unexpected core module")
        check(core["parameters"]["FIRMWARE_INIT_FILE"]["value"] == "ps.mem", "Unexpected core firmware")
        check(number(core["ports"]["s_axi_aclk"]["parameters"]["FREQ_HZ"]["value"]) == 100000000,
              "Core clock metadata is not 100 MHz")
        interface = core["interface_ports"]["S_AXI"]["parameters"]
        for name, value in (("FREQ_HZ", "100000000"), ("ADDR_WIDTH", "18"),
                            ("DATA_WIDTH", "32"), ("PROTOCOL", "AXI4LITE")):
            check(interface[name]["value"] == value, "Core AXI metadata mismatch: " + name)
        for endpoints in (("ps7/M_AXI_GP0", "axi_bus/S00_AXI"), ("axi_bus/M00_AXI", "k4_core/S_AXI")):
            check(any(set(endpoints).issubset(set(net.get("interface_ports", [])))
                      for net in design["interface_nets"].values()), "AXI interface wiring mismatch: " + str(endpoints))
        segments = design["addressing"]["/ps7"]["address_spaces"]["Data"]["segments"]
        mapped = [segment for segment in segments.values() if segment["address_block"] == "/k4_core/S_AXI/reg0"]
        check(len(mapped) == 1, "Expected exactly one PS data mapping for k4_core")
        if len(mapped) == 1:
            details["address"] = dict(base=number(mapped[0]["offset"]), span=number(mapped[0]["range"]))
            check(details["address"] == dict(base=0x40000000, span=0x40000), "Core AXI address/range mismatch")

        # Cross-check generated synthesis HDL, so stale products cannot pass
        # merely because the editable BD JSON has been repaired.
        generated = (bd_path.parent / design["design_info"]["gen_directory"]).resolve()
        hdl = read(generated / "synth/system.v", structured=False)

        def ports(cell):
            match = re.search(r"\b\w+\s+" + re.escape(cell) + r"\s*\((.*?)\);", hdl, re.S)
            if not match:
                raise ValueError("Generated HDL is missing instance " + cell)
            return dict(re.findall(r"\.([A-Za-z_][\w]*)\s*\(([^()]*)\)", match[1]))

        reset_ports, ps_ports, core_ports, bus_ports = map(ports, ("reset_100m", "ps7", "k4_core", "axi_bus"))
        for pin, driver in (("aux_reset_in", aux_cell), ("mb_debug_sys_rst", debug_cell), ("dcm_locked", lock_cell)):
            check(reset_ports[pin] == ports(driver)["dout"], "Generated HDL constant wiring mismatch: " + pin)
        check(reset_ports["ext_reset_in"] == ps_ports["FCLK_RESET0_N"], "Generated HDL external reset mismatch")
        for signal in (core_ports["s_axi_aclk"], reset_ports["slowest_sync_clk"], ps_ports["M_AXI_GP0_ACLK"],
                       *[bus_ports[name] for name in ("ACLK", "S00_ACLK", "M00_ACLK")]):
            check(signal == ps_ports["FCLK_CLK0"], "Generated HDL clock wiring mismatch")
        for signal in (core_ports["s_axi_aresetn"], bus_ports["S00_ARESETN"], bus_ports["M00_ARESETN"]):
            check(signal == reset_ports["peripheral_aresetn"], "Generated HDL peripheral reset mismatch")
        check(bus_ports["ARESETN"] == reset_ports["interconnect_aresetn"], "Generated HDL interconnect reset mismatch")
    except (OSError, ValueError, KeyError, TypeError, IndexError) as error:
        reasons.append("Cannot verify generated BD controls: " + str(error))
    return dict(passed=not reasons, reasons=reasons, details=details)


def collect(run):
    manifest = json.loads((run / "manifest.json").read_text(encoding="utf-8"))
    frozen_errors = []
    try:
        verify(run)
    except (OSError, ValueError, KeyError, RuntimeError) as error:
        frozen_errors.append(str(error))
    metrics = json.loads((run / "metrics.json").read_text(encoding="utf-8"))
    evidence = ROOT / "results/keccak_cpu/pynq" / run.name
    evidence.mkdir(parents=True, exist_ok=True)
    controls = bd_control_checks(run) if (run / "project").exists() else dict(
        passed=False, reasons=["No generated BD project is available"], details={"input_sha256": {}})
    outputs = {}
    for p in [run / "manifest.json", run / "metrics.json", run / "simulate.log", run / "simulation_reuse.json", *sorted((run / "reports").glob("*"))]:
        if p.is_file():
            rel = p.relative_to(run)
            dest = evidence / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(p, dest)
            outputs[str(rel)] = sha(p)
    # Preserve the actual independent reviewer, including when it is newer
    # than the immutable candidate. Never rewrite that candidate's manifest.
    helper_hash = sha(__file__)
    shutil.copyfile(__file__, evidence / "actual_collection_helper.py")
    frozen_helper_hash = manifest["inputs"].get("pynq_overlay.py", {}).get("sha256")
    for name in controls["details"]["input_sha256"]:
        target = evidence / "bd_control_inputs" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(run / name, target)
    host_checks = {}
    for name in ("mlkem1024.py", "mlkem1024.ipynb", "kat_vectors.json"):
        expected = manifest["inputs"].get("host/" + name, {}).get("sha256")
        path = run / "snapshot/host" / name
        actual = sha(path) if path.is_file() else None
        host_checks[name] = dict(frozen_sha256=expected, actual_sha256=actual,
                                 passed=expected is not None and actual == expected)
        if not host_checks[name]["passed"]:
            frozen_errors.append("Frozen host artifact mismatch: " + name)
    result = dict(scope="AXI wrapper RTL subset and Zynq PS block design physical implementation",
                  physical_board_tested=False, run_dir=str(run), metrics=metrics, output_sha256=outputs,
                  actual_collection_helper_sha256=helper_hash,
                  frozen_collection_helper_sha256=frozen_helper_hash,
                  collection_helper_matches_frozen=helper_hash == frozen_helper_hash,
                  bd_control_checks=controls, host_artifact_checks=host_checks,
                  frozen_input_errors=frozen_errors,
                  passed=metrics.get("passed") is True and controls["passed"] and not frozen_errors)
    if result["passed"]:
        # The release is created only after functional and physical gates passed.
        try:
            bundle = run / "bundle"
            bundle.mkdir(exist_ok=True)
            shutil.copyfile(run / "k4_accel.bit", bundle / "k4_accel.bit")
            with zipfile.ZipFile(run / "k4_accel.xsa") as z:
                names = [n for n in z.namelist() if n.endswith(".hwh")]
                if len(names) != 1:
                    raise RuntimeError("Expected one HWH in XSA, found " + str(names))
                (bundle / "k4_accel.hwh").write_bytes(z.read(names[0]))
            for name in host_checks:
                shutil.copyfile(run / "snapshot/host" / name, bundle / name)
                digest = sha(bundle / name)
                host_checks[name]["bundle_sha256"] = digest
                if digest != host_checks[name]["frozen_sha256"]:
                    raise RuntimeError("Bundle host artifact differs from frozen candidate: " + name)
            project = (run / "project/k4_pynq.xpr").resolve()
            (bundle / "README.txt").write_text(
                "ML-KEM-1024 PYNQ-Z2 overlay\n\n"
                "Offline RTL subset verification and physical implementation only.\n"
                "No on-board results have been collected for this release.\n"
                "Keep k4_accel.bit and k4_accel.hwh together beside mlkem1024.ipynb,\n"
                "mlkem1024.py, kat_vectors.json, and release_manifest.json.\n"
                "Open the notebook on the board to verify and run the official cases.\n\n"
                f"Original Vivado project: {project}\n"
                f"Original bitstream: {(bundle / 'k4_accel.bit').resolve()}\n"
                f"Original hardware handoff: {(bundle / 'k4_accel.hwh').resolve()}\n",
                encoding="utf-8")
            files = {p.name: sha(p) for p in bundle.iterdir() if p.is_file() and p.name != "release_manifest.json"}
            release = dict(schema=1, files=files, generated_utc=datetime.now(timezone.utc).isoformat(),
                run_dir=str(run), input_manifest_sha256=sha(run / "manifest.json"), physical_board_tested=False,
                actual_collection_helper_sha256=helper_hash,
                overlay=dict(bitstream="k4_accel.bit", base_address=0x40000000, address_range=0x40000,
                             id=0x4b344158, abi=1, frequency_hz=100000000, ram_bytes=131072))
            dump(bundle / "release_manifest.json", release)
            # Execute the exact frozen host verifier, without importing PYNQ
            # or downloading an overlay. This must precede publication.
            driver = runpy.run_path(str(bundle / "mlkem1024.py"))
            driver["verify_bundle"](bundle / "release_manifest.json")
            result["bundle_verification"] = dict(passed=True,
                verifier_sha256=sha(bundle / "mlkem1024.py"),
                release_manifest_sha256=sha(bundle / "release_manifest.json"))
            deployment = ROOT / "release/mlkem1024_pynq"
            deployment.mkdir(parents=True, exist_ok=True)
            for p in bundle.iterdir():
                if p.is_file():
                    shutil.copyfile(p, deployment / p.name)
            shutil.copyfile(bundle / "release_manifest.json", evidence / "release_manifest.json")
            result["release_directory"] = str(deployment)
            result["bitstream_sha256"] = files["k4_accel.bit"]
            result["hwh_sha256"] = files["k4_accel.hwh"]
        except Exception as error:
            result["passed"] = False
            result["bundle_verification"] = dict(passed=False, error=str(error))
    dump(evidence / "result.json", result)
    print("PYNQ_COLLECT " + str(evidence) + " passed=" + str(result["passed"]))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stage", choices=["prepare", "verify", "collect"])
    parser.add_argument("run", type=Path)
    parser.add_argument("--reuse-sim", type=Path)
    args = parser.parse_args()
    if args.stage == "prepare":
        prepare(args.run.resolve(), args.reuse_sim)
    else:
        globals()[args.stage](args.run.resolve())
